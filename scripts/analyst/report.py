#Генерация отчёта
from __future__ import annotations

from typing import Any


def _fmt(value: float | None, digits: int = 3) -> str:
    if value is None:
        return "—"
    return f"{value:.{digits}f}"


def render_markdown(result: dict[str, Any]) -> str:
    agent_name = result["target_agent"]
    agent = result["agents"][agent_name]
    worst = agent["worst_case"]

    lines = [
        "# Профиль устойчивости (Robustness Profile)",
        "",
        "Отчёт сгенерирован автоматически на основе логов прогона целевого агента.",
        "",
        "## 📊 Сводка по агенту",
        "",
        f"- **Целевой агент:** `{agent_name}`",
        f"- **Базовая точность (Baseline Accuracy):** {_fmt(agent['baseline_accuracy'])}",
        "  *(Доля правильных ответов на чистых, нематированных задачах).*",
        f"- **Оценка устойчивости (Robustness Score):** {_fmt(agent['robustness_score'])}",
        "  *(Показывает, какую долю качества агент сохраняет под шумом. 1.0 = не теряет ничего, 0.0 = полностью ломается).*",
        f"- **Покрытие (Coverage):** {agent['coverage']:.1%}",
        "  *(Доля проверенных комбинаций из 21 возможной: 7 типов шума × 3 уровня интенсивности).*",
        "",
        "## 🚨 Худший случай (Worst-case)",
        "",
        "Это самая проблемная комбинация шума. Именно на ней агент показывает наибольшее падение качества.",
        "",
        f"- **Тип мутации:** `{worst['mutation_type']}`",
        f"- **Интенсивность:** `{worst['intensity']}`",
        f"- **Точность на этой мутации:** {_fmt(worst['accuracy'])}",
        f"- **Падение относительно baseline (Delta):** {_fmt(worst['delta'])}",
        f"- **95% Доверительный интервал:** [{_fmt(worst['ci_low'])}, {_fmt(worst['ci_high'])}]",
        "",
        "## 📋 Все проверенные комбинации",
        "",
        "| Тип мутации | Интенсивность | Количество тестов (n) | Точность (accuracy) | Падение (delta) | 95% ДИ | Ср. шагов | Ср. стоимость ($) |",
        "|---|---|---:|---:|---:|---|---:|---:|",
    ]

    for combo in agent["combos"]:
        ci = f"{_fmt(combo['ci_low'])}, {_fmt(combo['ci_high'])}"
        lines.append(
            "| {mutation_type} | {intensity} | {n} | {accuracy} | {delta} | {ci} | {steps} | {cost} |".format(
                mutation_type=combo["mutation_type"],
                intensity=combo["intensity"],
                n=combo["n"],
                accuracy=_fmt(combo["accuracy"]),
                delta=_fmt(combo["delta"]),
                ci=ci,
                steps=_fmt(combo["avg_steps"], 2),
                cost=_fmt(combo["avg_cost_usd"], 4),
            )
        )

    lines += [
        "",
        "## 📖 Как читать эти метрики",
        "",
        "1. **Падение (Delta):** Разница между точностью на чистом вводе и на мутации. Если Delta = 0.40, это значит, что агент потерял 40% правильных ответов по сравнению с базой.",
        "2. **Количество тестов (n):** Если `n` маленькое (например, 1–2), метрики нестабильны. Чем больше `n`, тем выше доверие к цифрам.",
        "3. **95% ДИ (Доверительный интервал):** Показывает разброс. Широкий интервал означает, что данных мало. Узкий — что оценка надежная.",
        "4. **Ср. стоимость и шаги:** Показывают, насколько дороже и дольше агент работает под шумом.",
        "",
        "## 💡 Интерпретация для команды",
        "",
        "Сравнивайте не только среднюю точность, но и **худший случай**. Если Delta на worst-case сильно выше средней, значит, агент имеет критическую уязвимость к конкретному типу шума. Именно эту комбинацию нужно передать Мутатору и Исполнителю для доработки.",
        "",
    ]
    return "\n".join(lines)
